/**
 * Wording that belongs to one page, in both languages. The build stops when a key is missing on either side.
 * `{name}` placeholders are filled by the returned function.
 */
export function pageCopy<K extends string>(lang: Lang, where: string, en: Record<K, string>, mr: Record<K, string>) {
  for (const k of Object.keys(en)) if (!(k in mr)) throw new Error(`${where}: Marathi text is missing for "${k}"`);
  for (const k of Object.keys(mr)) if (!(k in en)) throw new Error(`${where}: "${k}" is in the Marathi text but not the English text`);
  const dict = lang === 'mr' ? mr : en;
  return (key: K, vars?: Record<string, string | number>) => {
    let s = dict[key];
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
    return s;
  };
}
