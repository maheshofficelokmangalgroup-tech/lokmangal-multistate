const dictionaries: Record<Lang, Record<Key, string>> = { en, mr };

// A missing translation would show an English key name to visitors, so it fails the build instead.
for (const key of Object.keys(en) as Key[]) {
  if (!(key in mr)) throw new Error(`Marathi text is missing for "${key}" (src/i18n/ui.ts)`);
}
for (const key of Object.keys(mr)) {
  if (!(key in en)) throw new Error(`"${key}" is in the Marathi text but not the English text (src/i18n/ui.ts)`);
}

export type T = (key: Key, vars?: Record<string, string | number>) => string;

export function useT(lang: Lang): T {
  const dict = dictionaries[lang];
  return (key, vars) => {
    let s = dict[key];
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
    return s;
  };
}

